// Regenerates po/gnometangle.pot, the template translators start from:
//   strings wrapped in _() in src/, extracted with xgettext
//   action and group labels, read from src/core/actions.ts (which can't import gettext)

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadActions } from './load-actions.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const metadata = JSON.parse(readFileSync(join(root, 'metadata.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const sources = ['src/extension.ts', 'src/gnome-shortcuts.ts', 'src/indicator.ts', 'src/prefs.ts'];
const extracted = execFileSync(
  'xgettext',
  [
    '--language=JavaScript',
    '--from-code=UTF-8',
    '--keyword=_',
    '--add-comments=Translators',
    `--package-name=${metadata.name}`,
    `--package-version=${pkg.version}`,
    `--msgid-bugs-address=${metadata.url}/issues`,
    '--output=-',
    ...sources,
  ],
  { cwd: root, encoding: 'utf8' },
);

// Swap xgettext's header for a stable one, so the template only changes when strings do.
const body = extracted.slice(extracted.indexOf('\n\n') + 2);

const quote = (s) => JSON.stringify(s);
const known = new Set([...body.matchAll(/^msgid (".*")$/gm)].map((m) => JSON.parse(m[1])));
const { ACTIONS, GROUP_LABELS } = await loadActions(root);
const labels = [...Object.values(GROUP_LABELS), ...ACTIONS.map((a) => a.label)].filter(
  (label, i, all) => all.indexOf(label) === i && !known.has(label),
);

const header = `# Translations for ${metadata.name}.
# Generated by scripts/pot.mjs. Do not edit; run \`pnpm pot\` instead.
msgid ""
msgstr ""
"Project-Id-Version: ${metadata.name} ${pkg.version}\\n"
"Report-Msgid-Bugs-To: ${metadata.url}/issues\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
`;
const labelEntries = labels.map((label) => `#: src/core/actions.ts\nmsgid ${quote(label)}\nmsgstr ""\n`);

mkdirSync(join(root, 'po'), { recursive: true });
writeFileSync(
  join(root, 'po', `${metadata['gettext-domain']}.pot`),
  [header, body.trimEnd() + '\n', ...labelEntries].join('\n'),
);
console.log(`Wrote po/${metadata['gettext-domain']}.pot`);
