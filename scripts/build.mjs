// Builds the extension into dist/:
//   extension.js, prefs.js   bundled with esbuild (GNOME imports stay external)
//   schemas/*.gschema.xml    generated from src/core/actions.ts
//   metadata.json            with version-name taken from package.json
//   stylesheet.css, icons/   copied from src/
//   locale/                  compiled from po/*.po
// Flags:
//   --zip      also write <uuid>.shell-extension.zip in the repo root
//   --compile  also compile schemas in dist/ (needed for manual installs on GNOME 45)

import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

import { loadActions } from './load-actions.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GETTEXT_DOMAIN = JSON.parse(readFileSync(join(root, 'metadata.json'), 'utf8'))['gettext-domain'];
const dist = join(root, 'dist');
const args = new Set(process.argv.slice(2));

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'schemas'), { recursive: true });

await esbuild.build({
  entryPoints: [join(root, 'src/extension.ts'), join(root, 'src/prefs.ts')],
  outdir: dist,
  bundle: true,
  format: 'esm',
  target: 'firefox115', // SpiderMonkey 115 ships with GJS 1.78 (GNOME 45)
  platform: 'neutral',
  external: ['gi://*', 'resource://*'],
  legalComments: 'none',
  logLevel: 'warning',
});

// Evaluate the action list to generate the schema, so keys and defaults never drift.
const actionsModule = await loadActions(root);
writeFileSync(join(dist, 'schemas', `${actionsModule.SCHEMA_ID}.gschema.xml`), schemaXml(actionsModule));

// Compiled translations, one po/<lang>.po per language.
const poDir = join(root, 'po');
for (const file of existsSync(poDir) ? readdirSync(poDir).filter((f) => f.endsWith('.po')) : []) {
  const out = join(dist, 'locale', basename(file, '.po'), 'LC_MESSAGES');
  mkdirSync(out, { recursive: true });
  execFileSync('msgfmt', ['--check', '-o', join(out, `${GETTEXT_DOMAIN}.mo`), join(poDir, file)], {
    stdio: 'inherit',
  });
}

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const metadata = JSON.parse(readFileSync(join(root, 'metadata.json'), 'utf8'));
metadata['version-name'] = pkg.version;
writeFileSync(join(dist, 'metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`);
cpSync(join(root, 'LICENSE'), join(dist, 'LICENSE'));
cpSync(join(root, 'src/stylesheet.css'), join(dist, 'stylesheet.css'));
cpSync(join(root, 'src/icons'), join(dist, 'icons'), { recursive: true });

if (args.has('--compile')) {
  execFileSync('glib-compile-schemas', ['--strict', join(dist, 'schemas')], { stdio: 'inherit' });
}

if (args.has('--zip')) {
  const zipPath = join(root, `${metadata.uuid}.shell-extension.zip`);
  rmSync(zipPath, { force: true });
  execFileSync('zip', ['-qr', zipPath, '.'], { cwd: dist, stdio: 'inherit' });
  console.log(`Wrote ${zipPath}`);
}

function escapeXml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function schemaXml({ ACTIONS, SETTINGS, SCHEMA_ID, SCHEMA_PATH }) {
  const intKey = (name, def, min, max, summary) =>
    `    <key name="${name}" type="i">\n      <default>${def}</default>\n      <range min="${min}" max="${max}"/>\n      <summary>${summary}</summary>\n    </key>`;
  const boolKey = (name, def, summary) =>
    `    <key name="${name}" type="b">\n      <default>${def}</default>\n      <summary>${summary}</summary>\n    </key>`;

  const keys = [
    intKey(SETTINGS.gapSize, 0, 0, 64, 'Gap between windows and screen edges in pixels'),
    intKey(SETTINGS.almostMaximizePercent, 90, 50, 100, 'Almost Maximize size as a percent of the work area'),
    intKey(SETTINGS.sizeStep, 30, 5, 200, 'Pixels added or removed per side by Make Larger and Make Smaller'),
    boolKey(SETTINGS.cycleSizes, true, 'Cycle through 1/2, 2/3 and 1/3 when a shortcut is repeated'),
    boolKey(SETTINGS.overrideConflicts, false, 'Temporarily remove GNOME shortcuts that conflict with ours'),
    boolKey(SETTINGS.showIndicator, true, 'Show the Gnometangle menu in the top bar'),
    `    <key name="${SETTINGS.overriddenShortcuts}" type="s">\n      <default>''</default>\n      <summary>Internal: original GNOME shortcuts saved while overridden (JSON)</summary>\n    </key>`,
    ...ACTIONS.map((a) => {
      const def = `[${a.defaults.map((d) => `'${escapeXml(d)}'`).join(', ')}]`;
      return `    <key name="${a.id}" type="as">\n      <default>${def}</default>\n      <summary>${a.label}</summary>\n    </key>`;
    }),
  ];

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build.mjs from src/core/actions.ts. Do not edit. -->
<schemalist>
  <schema id="${SCHEMA_ID}" path="${SCHEMA_PATH}">
${keys.join('\n')}
  </schema>
</schemalist>
`;
}
